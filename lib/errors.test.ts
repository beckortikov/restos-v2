import { describe, it, expect } from 'vitest'
import { humanizeError } from './errors'
import { V4Error } from './api'

// Регрессия v3.16.89: humanizeError отдавал общий текст по коду ВСЕГДА, если код
// известен, поэтому все 22 русских сообщения бэка были недостижимы. Кассир вместо
// «оформите двумя документами» видел «обновите страницу и попробуйте снова» —
// совет, который в этих случаях ничего не чинит.
//
// Правило: русский текст бэка написан ДЛЯ пользователя и выигрывает у кода.
// Английский — внутренняя ошибка для лога, его показывать нельзя.

function envelopeError(code: string, message: string): V4Error {
  return new V4Error(409, { code, message })
}

describe('humanizeError', () => {
  it('показывает русское сообщение бэка вместо общего текста по коду', () => {
    const e = envelopeError('CONFLICT', 'возврат больше остатка долга (220) — оформите двумя документами')
    expect(humanizeError(e)).toBe('возврат больше остатка долга (220) — оформите двумя документами')
  })

  it('не показывает английские сообщения — это внутренние ошибки для лога', () => {
    const e = envelopeError('CONFLICT', 'return exceeds remaining debt 220')
    expect(humanizeError(e)).toBe('Действие конфликтует с текущим состоянием. Обновите страницу и попробуйте снова.')
  })

  it('без сообщения отдаёт общий текст по коду', () => {
    expect(humanizeError(envelopeError('NOT_FOUND', ''))).toBe('Запись не найдена. Возможно, её уже удалили.')
  })

  it('не пропускает тех-мусор, даже если в нём есть кириллица', () => {
    const e = envelopeError('CONFLICT', '{"detail":"ошибка","SQLSTATE":"23505"}')
    expect(humanizeError(e)).toBe('Действие конфликтует с текущим состоянием. Обновите страницу и попробуйте снова.')
  })
})
