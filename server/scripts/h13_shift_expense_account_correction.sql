-- счёт» (v3.16.94+).
-- ============================================================================
--
-- КОНТЕКСТ. До v3.16.94 расход из кассы смены (cash_out с категорией: «Закупка
-- продуктов», «Ремонт» и т.п.) создавал financial_operation, но НЕ уменьшал
-- баланс счёта. При этом выручка кредитовала счёт полностью. Итог: «Денежные
-- средства» в Балансе завышены на сумму ВСЕХ прошлых кассовых расходов.
--
-- С v3.16.94 новые кассовые расходы дебетуют счёт корректно. Этот скрипт —
-- разовое выравнивание ИСТОРИИ: уменьшает баланс каждого счёта на сумму прошлых
-- shift_expense-финопов, созданных ДО деплоя фикса.
--
-- ЗАПУСК (на кассе, где крутится встроенный Postgres):
--   1. Остановите кассу (чтобы никто не пробивал во время коррекции).
--   2. Подставьте ':cutoff' — момент, КОГДА выкатили v3.16.94+ на эту кассу
--      (любой момент между «до фикса были только старые расходы» и «первым новым
--      расходом»). Если запускаете сразу после первого обновления и до первой
--      новой смены — можно взять now().
--   3. Сначала прогоните БЛОК ПРЕВЬЮ, сверьте суммы.
--   4. Затем БЛОК ПРИМЕНЕНИЯ (в транзакции). Откат — ROLLBACK вместо COMMIT.
--
-- ВАЖНО: скрипт не идемпотентен. Повторный запуск спишет ещё раз. Запускать
-- РОВНО ОДИН РАЗ на кассу. cutoff отсекает новые (уже корректно дебетующие)
-- расходы, чтобы их не задвоить.
-- ============================================================================

-- ── БЛОК ПРЕВЬЮ (только чтение) ─────────────────────────────────────────────
-- Сколько будет списано с каждого счёта. Проверьте перед применением.
SELECT
  fo.account_id,
  fa.name                         AS account_name,
  fa.balance                      AS balance_now,
  COALESCE(SUM(fo.amount), 0)     AS correction,
  fa.balance - COALESCE(SUM(fo.amount), 0) AS balance_after,
  COUNT(*)                        AS ops_count
FROM financial_operations fo
JOIN financial_accounts fa ON fa.id = fo.account_id
WHERE fo.type = 'out'
  AND fo.source_ref LIKE 'shift_expense:%'
  AND fo.created_at < :cutoff          -- напр. '2026-07-18 00:00:00+00' или now()
  -- Тот же ресторан, если БД мультитенантная (обычно на кассе один):
  -- AND fo.restaurant_id = :restaurant_id
GROUP BY fo.account_id, fa.name, fa.balance
ORDER BY correction DESC;

