--
-- 081_nomenclature_tombstone — удаление записи из общего каталога сети с
-- распространением на филиалы (ADR-003, Фаза Г, последний пункт).
--
-- Удаления из каталога не существовало вовсе — ни ручки, ни механизма. При
-- этом дубли в каталоге ЗАКОНОМЕРНЫ: запись рождается автоматически при первой
-- отправке товара, поэтому «Мясо» одного филиала и «Мясо говяжье» другого дают
-- две записи об одном продукте. Страница «Сопоставление товаров» об этом прямо
-- предупреждает, но убрать лишнюю запись было нельзя.
--
-- Почему tombstone (мягкое удаление), а не DELETE: down-sync устроен как
-- «central отдаёт своё состояние, филиал применяет insert-if-absent». В такой
-- схеме исчезновение строки НЕ ОТЛИЧИМО от «её просто не прислали» — филиал
-- сохранил бы удалённую запись навсегда. Помеченная строка, наоборот, доезжает
-- и несёт явное «этой записи больше нет».
--
-- Что делает филиал, получив tombstone, — вопрос принципиальный: он
-- ОТВЯЗЫВАЕТ свой товар (ingredients.nomenclature_id = NULL), но НЕ удаляет
-- его. У товара есть остаток и вся история движений; удаление уничтожило бы
-- складские данные ради уборки справочника. Смысл операции — «перестать быть
-- сетевым», а не «стереть у всех».
ALTER TABLE nomenclature
  ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ;

-- Живой каталог (deleted_at IS NULL) читается на каждом тике down-sync и на
-- каждом открытии экрана — частичный индекс держит выборку дешёвой, не
-- утяжеляя вставку tombstone'ов.
CREATE INDEX IF NOT EXISTS idx_nomenclature_live
  ON nomenclature(account_id) WHERE deleted_at IS NULL;
-- +goose StatementEnd

-- +goose Down
-- +goose StatementBegin
DROP INDEX IF EXISTS idx_nomenclature_live;
ALTER TABLE nomenclature DROP COLUMN IF EXISTS deleted_at;
-- +goose StatementEnd
