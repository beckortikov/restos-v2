-- 079_expense_for_branch — расходы, оплаченные ОДНИМ узлом сети ЗА ДРУГОЙ
-- (ADR-003, Фаза Р). Ведущий случай: владелец выдаёт зарплату сотрудникам
-- филиалов из кассы центрального узла.
--
-- Проблема в учёте, а не в переводе денег. Затрата принадлежит филиалу (это
-- его ФОТ, его юнит-экономика), а деньги ушли со счёта центра. Записать
-- операцию только в одном месте — значит соврать в одном из двух отчётов:
--   • только на центре → у филиала пропадает ФОТ, его прибыль завышена, и,
--     что опаснее, зарплатный кап филиала выплату НЕ ВИДИТ (он ищет проводки
--     в своей БД по source_ref+тегу периода) → её можно выплатить второй раз;
--   • только на филиале → у центра не сходится касса: деньги ушли, а расхода
--     нет.
--
-- Поэтому проводки ДВЕ, и каждая помечена своей стороной сделки:
--
--   target_restaurant_id  — на проводке ПЛАТЕЛЬЩИКА: «заплатил за этот филиал».
--     Такая проводка исключается из ОПиУ плательщика (applyOpexFilter):
--     затрата не его. В ДДС плательщика остаётся — деньги реально ушли.
--
--   paid_by_restaurant_id — на ЗЕРКАЛЬНОЙ проводке у филиала: «за нас заплатил
--     этот узел». Без account_id и без движения баланса: на счетах филиала
--     ничего не происходило. Попадает в его ОПиУ (затрата его) и исключается
--     из ДДС — его касса не пустела. Из сетевого ДДС исключается по той же
--     причине: иначе один платёж посчитался бы дважды.
--
-- Зарплатный кап филиала специально НЕ трогаем: он ищет по category +
-- source_ref + тегу периода в description, без учёта счёта, — зеркальная
-- проводка попадает в его выборку сама и закрывает риск двойной выплаты.
ALTER TABLE financial_operations
  ADD COLUMN IF NOT EXISTS target_restaurant_id UUID,
  ADD COLUMN IF NOT EXISTS paid_by_restaurant_id UUID;

-- Down-sync ищет зеркала, адресованные конкретному филиалу; частичный индекс
-- держит выборку дешёвой (таких строк единицы против всего журнала операций).
CREATE INDEX IF NOT EXISTS idx_finops_target
  ON financial_operations(target_restaurant_id) WHERE target_restaurant_id IS NOT NULL;
