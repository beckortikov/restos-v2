--
-- 080_branch_sync_tokens — персональный sync-секрет каждого филиала
-- (ADR-003, Фаза Г).
--
-- До этого вся сеть жила на ОДНОМ общем секрете (RESTOS_SYNC_TOKEN): его
-- получал каждый филиал при подключении по коду. Отсюда два следствия, и оба
-- плохие.
--
-- 1. Отключить филиал по-настоящему было нельзя. DetachBranch (Фаза У) убирает
--    его из состава сети, но пуши он слать не перестаёт: central видит лишь
--    «пришёл кто-то с правильным секретом сети» и отличить узлы не может. Об
--    этом честно написано и в коде, и в диалоге отключения — теперь ограничение
--    снимается.
-- 2. Компрометация одного филиала = компрометация всей сети: сменить секрет
--    можно было только сразу у всех, перенастраивая каждую кассу.
--
-- Хранится ХЕШ (SHA-256), не сам токен: на central в открытом виде он не нужен
-- — токен выдаётся филиалу ровно один раз, в ответе на погашение кода. Утечка
-- базы central при этом не даёт возможности выдать себя за филиал.
--
-- Обратная совместимость обязательна: уже работающие филиалы знают только
-- общий секрет, и ломать их нельзя. SyncAuth принимает оба варианта — сначала
-- ищет пер-филиальный по хешу, затем сверяет с общим (легаси). Общий секрет
-- перестанет работать, когда все филиалы перевыпустят токены; принудительной
-- миграции нет.
ALTER TABLE restaurants
  ADD COLUMN IF NOT EXISTS sync_token_hash TEXT;

-- Поиск идёт ПО ХЕШУ на каждом запросе /sync/* — индекс обязателен.
CREATE INDEX IF NOT EXISTS idx_restaurants_sync_token_hash
  ON restaurants(sync_token_hash) WHERE sync_token_hash IS NOT NULL;
-- +goose StatementEnd

