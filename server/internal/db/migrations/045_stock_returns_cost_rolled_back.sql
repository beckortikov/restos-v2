-- 045_stock_return_lines.cost_rolled_back — сторно обязано зеркалить возврат.
--
-- Проблема: возврат откатывает средневзвешенную себестоимость только если с
-- момента приёмки НЕ было расхода (иначе формула даёт цену, которой не было ни
-- в одной накладной — см. 042 и v3.16.88). А сторно ВСЕГДА проводит товар назад
-- по формуле приёмки. Асимметрия → цикл «возврат + сторно» не возвращает
-- исходное состояние, а завышает стоимость запасов:
--
--   было:           10кг×10 + 10кг×20, расход 5кг → qty=15 price=15    (225)
--   возврат 10кг:   цену НЕ трогаем (был расход)  → qty=5  price=15    (75)
--   сторно:         формула приёмки               → qty=15 price=18.33 (275)
--
-- 50 из воздуха, и дальше это едет в COGS. Ошибся кладовщик, отменил — а след
-- в себестоимости остался, и увидеть его неоткуда.
--
-- Чинится тем, что сторно узнаёт, что именно делал возврат. Раньше узнать было
-- негде: решение принималось в рантайме по наличию расхода и не сохранялось.
--
-- Флаг на СТРОКЕ, а не на документе: расход проверяется по каждому ингредиенту
-- отдельно, поэтому в одном возврате товар A мог откатиться, а B — нет.
--
--   true  — возврат откатил цену → сторно применяет формулу приёмки (точно
--           восстанавливает исходную цену: операции взаимно обратны);
--   false — возврат цену не трогал → сторно возвращает только количество.
--
-- Default false безопасен для уже существующих возвратов: сторно старого
-- возврата не тронет цену. Консервативно — лучше не двигать цену вовсе, чем
-- двигать в неизвестную сторону.
--
ALTER TABLE stock_return_lines
  ADD COLUMN IF NOT EXISTS cost_rolled_back BOOLEAN NOT NULL DEFAULT false;
